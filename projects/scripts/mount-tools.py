#!/usr/bin/env python3
"""Mount the tracker's agent tools into a dsh profile's standard preset.

The Harness's `tools` service is agent-scoped, so the tracker's root row only
serves the board panel. The tools need a row inside an agent preset.

A partial override does not work: writing only `config.plugins` with one entry
REPLACES the preset's whole plugin list and removes every shipped agent tool.
So this writes the complete list — the shipped rows copied verbatim, plus the
tracker — which is the same thing the Web UI's preset editor produces.

Because the list is a copy, it freezes at the upstream state it was taken from.
Re-run this after upgrading the Harness to pick up new shipped tools. The block
it writes is delimited, so re-running replaces it cleanly, and deleting the
block restores the stock preset.

  ./scripts/mount-tools.py --harness /path/to/deepseek-harness --profile web
  ./scripts/mount-tools.py --profile web --remove
"""

import argparse
import re
import sys
from pathlib import Path

BEGIN = "# >>> dsh-projects: agent tools (generated by scripts/mount-tools.py) >>>"
END = "# <<< dsh-projects: agent tools <<<"
PRESET = "standard"


def shipped_plugins(harness: Path) -> list[str]:
    """The standard preset's `plugins:` block, verbatim, as source lines."""
    patch = harness / "packages/bundle/web-app/presets/standard.patch.yml"
    if not patch.is_file():
        sys.exit(f"not a harness checkout: {patch} is missing")
    lines = patch.read_text().split("\n")
    try:
        start = next(i for i, line in enumerate(lines) if re.match(r"^\s+plugins:\s*$", line))
    except StopIteration:
        sys.exit(f"no plugins: block found in {patch}")
    indent = len(lines[start]) - len(lines[start].lstrip())
    body = []
    for line in lines[start + 1:]:
        if line.strip() and (len(line) - len(line.lstrip())) <= indent:
            break
        body.append(line.rstrip())
    while body and not body[-1].strip():
        body.pop()
    if not body:
        sys.exit("the shipped plugins block is empty — refusing to write an override")
    return body, indent


def reindent(lines: list[str], was: int, now: int) -> list[str]:
    """Shifts a captured block to the indentation the override needs."""
    shift = now - was
    out = []
    for line in lines:
        if not line.strip():
            out.append("")
        elif shift >= 0:
            out.append(" " * shift + line)
        else:
            out.append(line[-shift:])
    return out


def strip_block(text: str) -> str:
    """Removes a previously generated block, leaving the rest untouched."""
    if BEGIN not in text:
        return text
    head, rest = text.split(BEGIN, 1)
    if END not in rest:
        sys.exit("found an opening marker with no closing marker; fix the file by hand")
    _, tail = rest.split(END, 1)
    return (head.rstrip() + "\n" + tail.lstrip("\n")).rstrip() + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--harness", type=Path, help="path to a deepseek-harness checkout")
    parser.add_argument("--profile", default="web", help="profile name under $DSH_HOME/profiles")
    parser.add_argument("--remove", action="store_true", help="remove the generated block")
    args = parser.parse_args()

    profile_patch = Path.home() / ".dsh/profiles" / args.profile / "cordis.patch.yml"
    if not profile_patch.is_file():
        sys.exit(f"no profile patch at {profile_patch}")
    original = profile_patch.read_text()

    if args.remove:
        profile_patch.write_text(strip_block(original))
        print(f"removed the generated block from {profile_patch}")
        return

    if args.harness is None:
        sys.exit("--harness is required unless --remove is given")

    body, indent = shipped_plugins(args.harness)
    # The override nests plugins two levels under the patch entry.
    plugins = reindent(body, indent + 2, 6)
    block = [
        BEGIN,
        "# The complete shipped list plus the tracker. A partial override would",
        "# REPLACE this list and remove every shipped agent tool.",
        f"- id: preset-{PRESET}",
        "  name: '@deepseek-ai/dsh-agent-preset'",
        "  config:",
        f"    id: {PRESET}",
        "    order: 1",
        "    plugins:",
        *plugins,
        "      - id: projects-tools",
        "        name: '@local/dsh-projects'",
        END,
    ]
    updated = strip_block(original).rstrip() + "\n" + "\n".join(block) + "\n"
    profile_patch.write_text(updated)
    print(f"wrote {len(plugins)} shipped plugin lines + the tracker into {profile_patch}")
    ids = re.findall(r"^\s+- id: ([a-z0-9-]+)", "\n".join(plugins), re.M)
    print(f"  shipped plugin rows preserved: {len(ids)}")


if __name__ == "__main__":
    main()
